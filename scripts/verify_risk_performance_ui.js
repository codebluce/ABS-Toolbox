const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.ABS_UI_PLAYWRIGHT||'/Users/wupeizhi.nolan/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const [desktop,mobile,output]=process.argv.slice(2);
fs.mkdirSync(output,{recursive:true});
async function check(risk){
 await risk.locator('#dynamic-tab').waitFor();
 const d=risk.frameLocator('#dynamic-frame'),s=risk.frameLocator('#static-frame');
 await d.locator('.card').first().waitFor();
 assert.equal(await d.locator('.balance').count(),0);
 assert.deepEqual(await d.locator('.rate').allTextContents(),['1.04%','0.51%','1.29%','0.60%','1.97%','0.70%','1.37%','0.61%']);
 assert.ok(!(await d.locator('body').innerText()).includes('-0.00'));
 assert.equal(await risk.locator('#period option').count(),9);
 await d.locator('#bad-chart [data-time-index="8"]').hover();
 assert.equal(await d.locator('.tooltip-table tbody tr').count(),4);
 await risk.locator('#asset').selectOption('白条');
 assert.equal(await d.locator('.card').count(),1);
 await risk.locator('#static-tab').click();
 await s.locator('.card').first().waitFor();
 assert.deepEqual(await s.locator('.card-name').allTextContents(),['赊销白条','信托白条']);
 assert.equal(await risk.locator('#period option').count(),5);
 await risk.locator('#asset').selectOption('all');
 assert.equal(await s.locator('.quality-change').first().textContent(),'+0.08 个百分点');
 assert.deepEqual((await s.locator('.quality-change').allTextContents()).slice(-3),['','','']);
 assert.ok((await s.locator('body').innerText()).includes('2025-12 白条取现'));
 await s.locator('details summary').click();
 const rules = await s.locator('#rules').innerText();
 assert.ok(!rules.includes('久期／年化周转次数'));
 assert.ok(!rules.includes('原表补充表述'));
 const aligned=await s.locator('.metrics').evaluateAll(nodes=>nodes.every(n=>{const r=[...n.querySelectorAll('.metric-row')].map(e=>e.getBoundingClientRect());return r.length===3&&Math.abs(r[0].top-r[2].top)<1}));
 assert.ok(aligned);
 await risk.locator('#period').selectOption('0');
 assert.ok((await s.locator('.quality-change').allTextContents()).every(v=>v===''));
 await risk.locator('#period').selectOption('4');
 await risk.locator('#asset').selectOption('白条取现');
 assert.equal(await s.locator('.quality-empty').count(),1);
 await risk.locator('#period').selectOption('3');
 assert.deepEqual(await s.locator('.card-name').allTextContents(),['取现']);
 await risk.locator('#asset').selectOption('all');
 await risk.locator('#period').selectOption('4');
 await s.locator('#bad-chart [data-index="4"]').hover();
 assert.equal(await s.locator('#tooltip tbody tr').count(),4);
 await risk.locator('#dynamic-tab').click();
 assert.equal(await risk.locator('#period').inputValue(),'8');
 for(const f of [risk,d])assert.equal(await f.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await risk.locator('#static-tab').click();
 assert.equal(await s.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
}
(async()=>{
 const b=await chromium.launch(),p=await b.newPage({viewport:{width:1440,height:1050}}),errors=[];
 p.on('pageerror',e=>errors.push(e.message));
 await p.goto(pathToFileURL(path.resolve(desktop)).href);
 await p.locator('.tab-button[data-module="asset_overview"]').click();
 assert.deepEqual(await p.locator('.sub-tabs-pane[data-module="asset_overview"] button').allTextContents(),['消金ABS','消金资产','风险表现']);
 await p.locator('.sub-tab-button[data-sub="risk_performance"]').click();
 const source=await p.locator('#risk-performance-frame').getAttribute('srcdoc');
 await check(p.frameLocator('#risk-performance-frame'));
 await p.frameLocator('#risk-performance-frame').frameLocator('#static-frame').locator('body').evaluate(()=>scrollTo(0,0));
 await p.screenshot({path:path.join(output,'desktop-static.png')});
 await p.frameLocator('#risk-performance-frame').locator('#dynamic-tab').click();
 await p.frameLocator('#risk-performance-frame').frameLocator('#dynamic-frame').locator('body').evaluate(()=>scrollTo(0,0));
 await p.screenshot({path:path.join(output,'desktop-dynamic.png')});
 await p.setViewportSize({width:390,height:844});
 await p.goto(pathToFileURL(path.resolve(mobile)).href);
 await p.locator('[data-act="tab:asset"]').click();
 assert.deepEqual(await p.locator('[data-act^="assetview:"]').allTextContents(),['消金ABS','消金资产','风险表现']);
 await p.locator('[data-act="assetview:risk"]').click();
 assert.equal(await p.locator('#m-risk-performance-frame').getAttribute('srcdoc'),source);
 await check(p.frameLocator('#m-risk-performance-frame'));
 await p.frameLocator('#m-risk-performance-frame').frameLocator('#static-frame').locator('body').evaluate(()=>scrollTo(0,0));
 await p.screenshot({path:path.join(output,'mobile-static.png')});
 await p.frameLocator('#m-risk-performance-frame').locator('#dynamic-tab').click();
 await p.frameLocator('#m-risk-performance-frame').frameLocator('#dynamic-frame').locator('body').evaluate(()=>scrollTo(0,0));
 await p.screenshot({path:path.join(output,'mobile-dynamic.png')});
 assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(output,'risk-ui.json'),JSON.stringify({status:'PASS',checks:['desktop mobile risk tab','same document','two pool modes','shared asset filtering','independent periods','dynamic rates only cards','static horizontal 3 metrics','change values and blanks','excluded disclosure records','column tooltips','no overflow'],errors},null,2));
 await b.close();console.log('PASS: risk performance desktop/mobile');
})().catch(e=>{console.error(e);process.exit(1)});
